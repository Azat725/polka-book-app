import { test, expect, loginApi, uploadApi } from './fixtures';

test('library controls organize, restore and customize an actual stored book', async ({ page, request, telegramUser }) => {
  const session = await loginApi(request, telegramUser);
  const headers = { Authorization: `Bearer ${session.token}` };
  const prefix = 'http://127.0.0.1:8000/api/v1';
  expect((await request.patch(`${prefix}/settings/`, { headers, data: { onboarding_done: true } })).ok()).toBeTruthy();
  const book = await uploadApi(request, session.token);
  await expect.poll(async () => (await request.get(`${prefix}/books/${book.id}/`, { headers })).json().then(body => body.processing_status), { timeout: 60_000 }).toBe('ready');
  await page.goto('/');
  await page.getByRole('navigation').getByRole('link', { name: 'Библиотека', exact: true }).click();
  await page.getByRole('button', { name: 'Порядок на полке', exact: true }).click();
  await page.getByRole('dialog').getByRole('textbox', { name: 'Название', exact: true }).fill('Quiet evenings');
  await page.getByRole('button', { name: 'Новая коллекция', exact: true }).click();
  await expect(page.getByRole('dialog').locator('.list-row').getByText('Quiet evenings', { exact: true })).toBeVisible();
  await page.getByRole('dialog').getByRole('button', { name: 'Закрыть', exact: true }).last().click();
  await page.getByRole('button', { name: 'О книге: Reading room', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Quiet evenings', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Избранное', exact: true }).check();
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить', exact: true }).click();
  await page.getByRole('combobox', { name: 'Коллекции', exact: true }).selectOption({ label: 'Quiet evenings' });
  await expect(page.locator('.book-card').filter({ hasText: 'Reading room' })).toBeVisible();
  await page.getByRole('button', { name: 'О книге: Reading room', exact: true }).click();
  await page.getByRole('button', { name: 'В корзину', exact: true }).click();
  await expect(page.locator('.book-card')).toHaveCount(0);
  await page.getByRole('button', { name: 'Ваш читательский уголок', exact: true }).click();
  await page.getByRole('button', { name: 'Корзина', exact: true }).click();
  await page.getByRole('button', { name: 'Восстановить: Reading room', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'В корзине пусто', exact: true })).toBeVisible();
  await page.getByRole('dialog').getByRole('button', { name: 'Закрыть', exact: true }).last().click();
  await expect(page.locator('.book-card').filter({ hasText: 'Reading room' })).toBeVisible();

  await page.getByRole('navigation').getByRole('link', { name: 'Настройки', exact: true }).click();
  await page.getByRole('button', { name: 'Terracotta', exact: true }).click();
  await page.getByRole('combobox', { name: 'Стиль полок', exact: true }).selectOption('wood');
  await page.getByRole('combobox', { name: 'Окружение книги', exact: true }).selectOption('paper');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Сохранено', exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: 'Язык', exact: true }).selectOption('en');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Saved', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Terracotta', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('navigation').getByRole('link', { name: 'Library', exact: true })).toBeVisible();
  const persisted = await (await request.get(`${prefix}/settings/`, { headers })).json();
  expect(persisted.theme).toBe('terracotta');
  expect(persisted.language).toBe('en');
  expect(persisted.shelf_style).toBe('wood');
  expect(persisted.reader_texture).toBe('paper');
});
